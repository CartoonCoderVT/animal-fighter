// Lola's faces: her base head with the eye and the mouth redrawn ([row, column, replacement]).
const face = (base, patches) => base.map((row, y) => {
  let r = row;
  for (const [py, px, str] of patches) if (py === y) r = r.slice(0, px) + str + r.slice(px + str.length);
  return r;
});
{
  const L = PARTS.rabbit, h = L.head;
  L.headBlink = face(h, [[11, 10, '22'], [12, 10, 'ee'], [13, 10, '22']]);
  L.headHurt = face(h, [[11, 10, 'e2'], [12, 10, '2e'], [13, 10, 'e2']]);
  L.headAngry = face(h, [[10, 10, 'ee'], [11, 10, '2e']]);
  L.headOpen = face(h, [[14, 11, 'ee'], [15, 11, 'e7']]);
  L.headDead = face(h, [[11, 10, 'e2'], [12, 10, '2e'], [13, 10, 'e2']]);
}

// Pain: the squeezed eyes of the hurt face with the open mouth of the shout.
for (const ch of Object.values(PARTS)) {
  const { headHurt: hurt, headOpen: open, headAngry: angry } = ch;
  if (hurt && open && angry) ch.headPain = hurt.map((row, y) => [...row].map((c, x) => (open[y][x] !== angry[y][x] ? open[y][x] : c)).join(''));
}
